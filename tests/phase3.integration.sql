-- Admin connection required; all business/account fixtures roll back.
BEGIN;
CREATE TEMP TABLE phase3_rls_before AS SELECT oid,relrowsecurity FROM pg_class WHERE relnamespace='public'::regnamespace AND relkind='r';
DO $$
DECLARE u public.users; a uuid; b uuid; product uuid; variant uuid; transfer uuid;
  request uuid:=gen_random_uuid(); receipt uuid; again uuid; local_id text:=gen_random_uuid()::text;
  payload jsonb; caught boolean; session jsonb; supplier uuid;
BEGIN
  SELECT * INTO u FROM public.users WHERE role='owner' AND auth_id IS NOT NULL AND coalesce(is_active,true) LIMIT 1;
  IF u.id IS NULL THEN RAISE EXCEPTION 'No owner fixture'; END IF;
  PERFORM set_config('request.jwt.claim.sub',u.auth_id::text,true);
  UPDATE public.tenants SET is_active=true,branches_limit=2147483647 WHERE id=u.tenant_id;
  a:=public.engine_add_store('__phase3_A__',''); b:=public.engine_add_store('__phase3_B__','');
  session:=public.engine_session();
  IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(session->'stores') AS s WHERE s->>'id'=b::text) THEN RAISE EXCEPTION 'Owner branch listing failed'; END IF;
  INSERT INTO public.products(tenant_id,name,base_price) VALUES(u.tenant_id,'__phase3_test__',200) RETURNING id INTO product;
  INSERT INTO public.product_variants(product_id,color,size,min_price,cost_price_avg) VALUES(product,'TEST','40',100,50) RETURNING id INTO variant;
  INSERT INTO public.inventory(store_id,variant_id,quantity) VALUES(a,variant,10);
  transfer:=public.engine_transfer(a,b,u.tenant_id,variant,3,request);
  IF transfer IS DISTINCT FROM public.engine_transfer(a,b,u.tenant_id,variant,3,request) THEN RAISE EXCEPTION 'Transfer idempotency failed'; END IF;
  IF (SELECT quantity FROM public.inventory WHERE store_id=a AND variant_id=variant)<>7 OR (SELECT quantity FROM public.inventory WHERE store_id=b AND variant_id=variant)<>3 THEN RAISE EXCEPTION 'Transfer counts failed'; END IF;
  payload:=jsonb_build_array(jsonb_build_object('variant_id',variant,'quantity',2,'final_price',150,'original_price',200));
  receipt:=public.engine_sync_sale_for_staff(a,u.tenant_id,local_id,payload,'cash',now(),u.id);
  again:=public.engine_sync_sale_for_staff(a,u.tenant_id,local_id,payload,'cash',now(),u.id);
  IF receipt IS DISTINCT FROM again OR (SELECT quantity FROM public.inventory WHERE store_id=a AND variant_id=variant)<>5 OR (SELECT synced_at FROM public.sales WHERE id=receipt) IS NULL THEN RAISE EXCEPTION 'Sale sync/idempotency failed'; END IF;
  caught:=false;
  BEGIN PERFORM public.engine_sync_sale_for_staff(a,u.tenant_id,gen_random_uuid()::text,payload,'cash',now(),gen_random_uuid()); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught THEN RAISE EXCEPTION 'Wrong author accepted'; END IF;
  caught:=false;
  BEGIN PERFORM public.engine_sync_sale_for_staff(a,u.tenant_id,gen_random_uuid()::text,jsonb_build_array(jsonb_build_object('variant_id',variant,'quantity',2,'final_price',99,'original_price',200)),'cash',now(),u.id); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught OR (SELECT quantity FROM public.inventory WHERE store_id=a AND variant_id=variant)<>5 THEN RAISE EXCEPTION 'Floor rollback failed'; END IF;
  UPDATE public.users SET store_id=a WHERE id=u.id;
  supplier:=public.engine_add_supplier(b,u.tenant_id,'__phase3_supplier__','','');
  IF NOT EXISTS(SELECT 1 FROM public.engine_suppliers(b,u.tenant_id) WHERE id=supplier) OR EXISTS(SELECT 1 FROM public.engine_suppliers(a,u.tenant_id) WHERE id=supplier) THEN RAISE EXCEPTION 'Owner cross-branch financial scope failed'; END IF;
  UPDATE public.users SET role='manager' WHERE id=u.id;
  session:=public.engine_session();
  IF jsonb_array_length(session->'stores')<>1 OR session->'stores'->0->>'id'<>a::text THEN RAISE EXCEPTION 'Manager branch leakage'; END IF;
  caught:=false;
  BEGIN PERFORM public.engine_transfer(a,b,u.tenant_id,variant,1,gen_random_uuid()); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught THEN RAISE EXCEPTION 'Manager transfer accepted'; END IF;
  caught:=false;
  BEGIN PERFORM public.engine_sync_sale_for_staff(b,u.tenant_id,gen_random_uuid()::text,payload,'cash',now(),u.id); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught THEN RAISE EXCEPTION 'Manager cross-store sale accepted'; END IF;
  caught:=false;
  BEGIN PERFORM * FROM public.engine_suppliers(b,u.tenant_id); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught THEN RAISE EXCEPTION 'Manager cross-branch financial read accepted'; END IF;
  UPDATE public.users SET role='employee' WHERE id=u.id;
  caught:=false;
  BEGIN PERFORM public.engine_activate('VTR-2147483647-test'); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught THEN RAISE EXCEPTION 'Employee activation accepted'; END IF;
  UPDATE public.users SET role='owner' WHERE id=u.id;
  UPDATE public.tenants SET is_active=false,subscription_end_date=now()-interval '1 day' WHERE id=u.tenant_id;
  caught:=false;
  BEGIN PERFORM public.engine_sync_sale_for_staff(a,u.tenant_id,gen_random_uuid()::text,payload,'cash',now(),u.id); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught THEN RAISE EXCEPTION 'Expired tenant accepted'; END IF;
  caught:=false;
  BEGIN PERFORM public.engine_activate('invalid'); EXCEPTION WHEN OTHERS THEN caught:=true; END;
  IF NOT caught THEN RAISE EXCEPTION 'Invalid key accepted'; END IF;
  PERFORM public.engine_activate('VTR-2147483647-test');
  IF NOT (SELECT is_active FROM public.tenants WHERE id=u.tenant_id) THEN RAISE EXCEPTION 'Activation failed'; END IF;
  IF EXISTS(SELECT 1 FROM phase3_rls_before old JOIN pg_class current ON current.oid=old.oid WHERE current.relrowsecurity IS DISTINCT FROM old.relrowsecurity) THEN RAISE EXCEPTION 'RLS flags changed'; END IF;
END $$;
ROLLBACK;
